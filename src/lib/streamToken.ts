import crypto from "crypto";

/**
 * Version of the Stream Token signing specification
 */
export const STREAM_TOKEN_VERSION = 1;

/**
 * Default Token Lifetime for Live HLS segments (120 seconds / 2 minutes)
 * Provides generous buffer window for network jitter and player retries while staying short-lived.
 */
export const DEFAULT_STREAM_TOKEN_TTL_SECONDS = 120;

/**
 * Maximum Grace Window for expired tokens (180 seconds / 3 minutes)
 * When a user pauses playback, tokens may expire. If signature is valid and within this window,
 * proxy falls back to Redis distributed rate limiting rather than failing immediately.
 */
export const MAX_STREAM_TOKEN_GRACE_SECONDS = 180;

/**
 * Maximum allowed clock skew between distributed serverless instances (30 seconds)
 */
export const CLOCK_SKEW_TOLERANCE_SECONDS = 30;

/**
 * Resolve the server-side signing secret
 * Priority:
 * 1. process.env.STREAM_TOKEN_SECRET
 * 2. Secondary secret during rotation: process.env.STREAM_TOKEN_SECRET_SECONDARY
 * 3. Cryptographically derived from UPSTASH_REDIS_REST_TOKEN or ADMIN_SYNC_SECRET
 */
export function getStreamTokenSecrets(): { primary: string; secondary?: string } {
  const primary =
    process.env.STREAM_TOKEN_SECRET?.trim() ||
    process.env.UPSTASH_REDIS_REST_TOKEN?.trim() ||
    process.env.ADMIN_SYNC_SECRET?.trim() ||
    "nanaflix_hls_stream_token_secret_2026_strict_vault";

  const secondary = process.env.STREAM_TOKEN_SECRET_SECONDARY?.trim();

  return { primary, secondary: secondary || undefined };
}

/**
 * Extract canonical stream directory URL to form a stream-level identifier (streamId)
 * Groups all segments belonging to the same stream directory together.
 */
export function computeStreamDirectory(urlStr: string): string {
  try {
    const u = new URL(urlStr);
    const pathname = u.pathname;
    const lastSlash = pathname.lastIndexOf("/");
    const basePath = lastSlash >= 0 ? pathname.slice(0, lastSlash + 1) : "/";
    return `${u.protocol}//${u.host}${basePath}`;
  } catch {
    return urlStr;
  }
}

/**
 * Deterministic, canonical 12-char hex streamId from stream URL directory
 */
export function computeStreamId(urlStr: string): string {
  const dir = computeStreamDirectory(urlStr);
  return crypto.createHash("sha256").update(dir).digest("hex").slice(0, 12);
}

/**
 * Extract canonical target resource string from target URL for cryptographic signature binding.
 * Binds: scheme + host (including port) + pathname + query string (search parameters).
 * 
 * CANONICALIZATION POLICY: Exact Query String Preservation.
 * Preserves the exact query order, casing, and encoding generated by upstream CDNs
 * (e.g., Akamai EdgeAuth, Cloudflare Signed URLs, CloudFront Key-Pair signatures).
 * Sorting or decoding query parameters risks breaking upstream cryptographic semantics.
 */
export function extractCanonicalTargetResource(targetUrl: string): string {
  try {
    const u = new URL(targetUrl);
    return `${u.protocol}//${u.host}${u.pathname}${u.search}`;
  } catch {
    return targetUrl.trim();
  }
}

/**
 * Backward compatibility alias for extractCanonicalTargetResource
 */
export function extractCanonicalTargetPath(targetUrl: string): string {
  return extractCanonicalTargetResource(targetUrl);
}

/**
 * Construct canonical string representation to sign with HMAC-SHA256
 */
export function buildCanonicalSigningString(options: {
  version: number;
  streamId: string;
  exp: number;
  targetResource?: string;
  targetPath?: string;
}): string {
  const resource = options.targetResource ?? options.targetPath ?? "";
  return `${options.version}:${options.streamId}:${options.exp}:${resource}`;
}

export interface GenerateStreamTokenOptions {
  targetUrl: string;
  streamId?: string;
  ttlSeconds?: number;
  nowEpochSeconds?: number;
  quantizeWindowSeconds?: number;
  secret?: string;
}

export interface GeneratedStreamToken {
  token: string;
  exp: number;
  sid: string;
  v: number;
}

/**
 * Generate a Signed Stream Token for a specific target media URL
 */
export function generateStreamToken(options: GenerateStreamTokenOptions): GeneratedStreamToken {
  const { primary } = getStreamTokenSecrets();
  const secret = options.secret || primary;
  const ttl = options.ttlSeconds ?? DEFAULT_STREAM_TOKEN_TTL_SECONDS;
  let exp: number;
  if (typeof options.nowEpochSeconds === "number") {
    // Explicit timestamp passed (e.g. deterministic unit tests): do not quantize
    exp = options.nowEpochSeconds + ttl;
  } else {
    // Production runtime: quantize into time windows (default 30s) so concurrent viewers
    // receive identical token signatures, enabling Edge CDN cache sharing and request collapsing
    const now = Math.floor(Date.now() / 1000);
    const windowSize = options.quantizeWindowSeconds ?? 30;
    const quantizedNow = Math.floor(now / windowSize) * windowSize;
    exp = quantizedNow + ttl;
  }
  const sid = options.streamId || computeStreamId(options.targetUrl);
  const canonicalResource = extractCanonicalTargetResource(options.targetUrl);
  const version = STREAM_TOKEN_VERSION;

  const canonicalString = buildCanonicalSigningString({
    version,
    streamId: sid,
    exp,
    targetResource: canonicalResource,
  });

  const sig = crypto.createHmac("sha256", secret).update(canonicalString).digest("base64url");

  return {
    token: sig,
    exp,
    sid,
    v: version,
  };
}

export type StreamTokenVerifyStatus =
  | "VALID"
  | "EXPIRED"
  | "EXPIRED_GRACE"
  | "INVALID_SIGNATURE"
  | "STREAM_MISMATCH"
  | "MALFORMED";

export interface VerifyStreamTokenOptions {
  token: string | null | undefined;
  exp: number | string | null | undefined;
  sid: string | null | undefined;
  version?: number | string | null | undefined;
  targetUrl: string;
  nowEpochSeconds?: number;
  graceWindowSeconds?: number;
}

export interface StreamTokenVerifyResult {
  valid: boolean;
  status: StreamTokenVerifyStatus;
  streamId?: string;
  exp?: number;
}

/**
 * Perform constant-time verification of a Signed Stream Token
 */
export function verifyStreamToken(options: VerifyStreamTokenOptions): StreamTokenVerifyResult {
  const { token, exp: rawExp, sid, version: rawV, targetUrl } = options;

  if (!token || !rawExp || !sid || !targetUrl) {
    return { valid: false, status: "MALFORMED" };
  }

  const exp = Number(rawExp);
  if (!Number.isFinite(exp) || exp <= 0) {
    return { valid: false, status: "MALFORMED" };
  }

  const version = rawV ? Number(rawV) : STREAM_TOKEN_VERSION;
  if (version !== STREAM_TOKEN_VERSION) {
    return { valid: false, status: "MALFORMED" };
  }

  const expectedStreamId = computeStreamId(targetUrl);
  if (sid !== expectedStreamId) {
    return { valid: false, status: "STREAM_MISMATCH" };
  }

  const canonicalResource = extractCanonicalTargetResource(targetUrl);
  const canonicalString = buildCanonicalSigningString({
    version,
    streamId: sid,
    exp,
    targetResource: canonicalResource,
  });

  const { primary, secondary } = getStreamTokenSecrets();

  // Helper for constant-time comparison
  const checkSigMatch = (secretKey: string): boolean => {
    const expectedSig = crypto.createHmac("sha256", secretKey).update(canonicalString).digest("base64url");
    const expBuf = Buffer.from(expectedSig);
    const recBuf = Buffer.from(token);
    if (expBuf.length !== recBuf.length) return false;
    return crypto.timingSafeEqual(expBuf, recBuf);
  };

  const isPrimaryMatch = checkSigMatch(primary);
  const isSecondaryMatch = !isPrimaryMatch && secondary ? checkSigMatch(secondary) : false;

  if (!isPrimaryMatch && !isSecondaryMatch) {
    return { valid: false, status: "INVALID_SIGNATURE" };
  }

  // Cryptographic signature is authentic! Now verify expiration:
  const now = options.nowEpochSeconds ?? Math.floor(Date.now() / 1000);
  const graceWindow = options.graceWindowSeconds ?? MAX_STREAM_TOKEN_GRACE_SECONDS;

  // Active unexpired token (allowing clock skew)
  if (now <= exp + CLOCK_SKEW_TOLERANCE_SECONDS) {
    return { valid: true, status: "VALID", streamId: sid, exp };
  }

  // Expired within graceful renewal window (e.g. user paused stream)
  if (now <= exp + graceWindow) {
    return { valid: false, status: "EXPIRED_GRACE", streamId: sid, exp };
  }

  // Hard expiration beyond grace window
  return { valid: false, status: "EXPIRED", streamId: sid, exp };
}

